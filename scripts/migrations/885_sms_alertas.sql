-- HU.130 (#885): notificaciones SMS.

ALTER TABLE aseo
ADD COLUMN IF NOT EXISTS stock_minimo
INTEGER NOT NULL DEFAULT 0;

ALTER TABLE maternidad
ADD COLUMN IF NOT EXISTS stock_minimo
INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS sms_destinatarios (
    id_destinatario BIGINT
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_usuario INTEGER NOT NULL
        REFERENCES usuarios(id_usuario),

    id_farmacia INTEGER NOT NULL
        REFERENCES farmacias(id_farmacia),

    telefono VARCHAR(16) NOT NULL
        CHECK (telefono ~ '^\+[1-9][0-9]{7,14}$'),

    autorizado BOOLEAN NOT NULL DEFAULT FALSE,
    autorizado_en TIMESTAMPTZ,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_sms_destinatario
        UNIQUE(id_usuario, id_farmacia, telefono),

    CONSTRAINT ck_sms_autorizacion
        CHECK (NOT autorizado OR autorizado_en IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS sms_alertas (
    id_alerta BIGINT
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_destinatario BIGINT NOT NULL
        REFERENCES sms_destinatarios(id_destinatario),

    id_farmacia INTEGER NOT NULL
        REFERENCES farmacias(id_farmacia),

    clave VARCHAR(90) NOT NULL,
    mensaje VARCHAR(1600) NOT NULL,

    activa BOOLEAN NOT NULL DEFAULT TRUE,

    estado VARCHAR(22) NOT NULL DEFAULT 'PENDIENTE'
        CHECK(estado IN (
            'PENDIENTE',
            'EN_PROCESO',
            'ACEPTADA',
            'SIMULADA',
            'FALLIDA',
            'INDETERMINADO'
        )),

    proveedor_referencia VARCHAR(80),
    error_detalle VARCHAR(250),

    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    procesado_en TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_sms_alerta_activa
ON sms_alertas(id_destinatario, clave)
WHERE activa;

CREATE INDEX IF NOT EXISTS ix_sms_alertas_pendientes
ON sms_alertas(id_alerta)
WHERE activa AND estado = 'PENDIENTE';
