-- HU-792: Auditoría de ajustes de existencias.
-- Requiere las tablas de inventario existentes.
-- Aplicar sobre PostgreSQL / Neon.

BEGIN;

CREATE TABLE IF NOT EXISTS auditoria_ajustes (

    id_ajuste BIGINT
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_lote INTEGER
        REFERENCES lotes(id_lote)
        ON DELETE RESTRICT,

    id_aseo INTEGER
        REFERENCES aseo(id_aseo)
        ON DELETE RESTRICT,

    id_maternidad INTEGER
        REFERENCES maternidad(id_maternidad)
        ON DELETE RESTRICT,

    id_usuario INTEGER NOT NULL
        REFERENCES usuarios(id_usuario),

    id_farmacia INTEGER NOT NULL
        REFERENCES farmacias(id_farmacia),

    motivo VARCHAR(250) NOT NULL
        CHECK (LENGTH(BTRIM(motivo)) > 0),

    cantidad_anterior INTEGER NOT NULL
        CHECK (cantidad_anterior >= 0),

    cantidad_nueva INTEGER NOT NULL
        CHECK (cantidad_nueva >= 0),

    diferencia INTEGER NOT NULL
        CHECK (diferencia <> 0),

    fecha_ajuste TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_ajuste_una_referencia
        CHECK (
            NUM_NONNULLS(
                id_lote,
                id_aseo,
                id_maternidad
            ) = 1
        ),

    CONSTRAINT chk_ajuste_diferencia
        CHECK (
            diferencia::BIGINT =
            cantidad_nueva::BIGINT -
            cantidad_anterior::BIGINT
        )
);

CREATE INDEX IF NOT EXISTS idx_ajustes_farmacia_fecha
ON auditoria_ajustes(id_farmacia, fecha_ajuste DESC);

CREATE INDEX IF NOT EXISTS idx_ajustes_lote
ON auditoria_ajustes(id_lote);

CREATE INDEX IF NOT EXISTS idx_ajustes_aseo
ON auditoria_ajustes(id_aseo);

CREATE INDEX IF NOT EXISTS idx_ajustes_maternidad
ON auditoria_ajustes(id_maternidad);

CREATE OR REPLACE FUNCTION fn_validar_auditoria_ajustes()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    farmacia_producto INTEGER;
    saldo_actual INTEGER;
BEGIN

    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION
            'Los registros de auditoría no pueden modificarse ni eliminarse';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM usuarios u
        JOIN farmacias f
            ON f.id_farmacia = u.id_farmacia
        WHERE u.id_usuario = NEW.id_usuario
          AND u.id_farmacia = NEW.id_farmacia
          AND UPPER(BTRIM(u.estado)) = 'ACTIVO'
          AND UPPER(BTRIM(f.estado)) = 'ACTIVA'
    ) THEN
        RAISE EXCEPTION
            'Usuario no activo o farmacia no autorizada';
    END IF;

    IF NEW.id_lote IS NOT NULL THEN

        SELECT m.id_farmacia, l.cantidad_actual
        INTO farmacia_producto, saldo_actual
        FROM lotes l
        JOIN medicamentos m
            ON m.id_medicamento = l.id_medicamento
        WHERE l.id_lote = NEW.id_lote;

    ELSIF NEW.id_aseo IS NOT NULL THEN

        SELECT a.id_farmacia, a.stock
        INTO farmacia_producto, saldo_actual
        FROM aseo a
        WHERE a.id_aseo = NEW.id_aseo;

    ELSIF NEW.id_maternidad IS NOT NULL THEN

        SELECT m.id_farmacia, m.stock
        INTO farmacia_producto, saldo_actual
        FROM maternidad m
        WHERE m.id_maternidad = NEW.id_maternidad;

    END IF;

    IF farmacia_producto IS DISTINCT FROM NEW.id_farmacia THEN
        RAISE EXCEPTION
            'El producto o lote no pertenece a la farmacia';
    END IF;

    IF saldo_actual IS DISTINCT FROM NEW.cantidad_nueva THEN
        RAISE EXCEPTION
            'El stock final debe aplicarse antes de registrar la auditoría';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_auditoria_ajustes
ON auditoria_ajustes;

CREATE TRIGGER trg_validar_auditoria_ajustes
BEFORE INSERT OR UPDATE OR DELETE
ON auditoria_ajustes
FOR EACH ROW
EXECUTE FUNCTION fn_validar_auditoria_ajustes();

COMMENT ON TABLE auditoria_ajustes IS
'HU-792: Historial inmutable de ajustes de existencias.';

COMMIT;
