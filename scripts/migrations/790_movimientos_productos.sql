-- CareStock - Movimientos de aseo y maternidad
-- Migracion asociada a la Issue #790.
-- Ejecutar en PostgreSQL/Neon antes de habilitar el servicio.

BEGIN;

CREATE TABLE IF NOT EXISTS movimientos_productos (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_aseo INTEGER
        REFERENCES aseo(id_aseo) ON DELETE RESTRICT,

    id_maternidad INTEGER
        REFERENCES maternidad(id_maternidad) ON DELETE RESTRICT,

    id_farmacia INTEGER NOT NULL
        REFERENCES farmacias(id_farmacia),

    id_usuario INTEGER NOT NULL
        REFERENCES usuarios(id_usuario),

    tipo_movimiento VARCHAR(8) NOT NULL
        CHECK (tipo_movimiento IN ('ENTRADA', 'SALIDA')),

    cantidad INTEGER NOT NULL
        CHECK (cantidad > 0),

    motivo VARCHAR(250) NOT NULL
        CHECK (LENGTH(BTRIM(motivo)) > 0),

    stock_anterior INTEGER NOT NULL
        CHECK (stock_anterior >= 0),

    stock_posterior INTEGER NOT NULL
        CHECK (stock_posterior >= 0),

    fecha_movimiento TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_movimiento_categoria
        CHECK (
            (id_aseo IS NOT NULL)
            <> (id_maternidad IS NOT NULL)
        ),

    CONSTRAINT chk_movimiento_saldo
        CHECK (
            (
                tipo_movimiento = 'ENTRADA'
                AND stock_posterior::BIGINT =
                    stock_anterior::BIGINT + cantidad::BIGINT
            )
            OR
            (
                tipo_movimiento = 'SALIDA'
                AND stock_posterior::BIGINT =
                    stock_anterior::BIGINT - cantidad::BIGINT
            )
        )
);

CREATE INDEX IF NOT EXISTS idx_movproductos_farmacia_fecha
    ON movimientos_productos (
        id_farmacia,
        fecha_movimiento DESC
    );

CREATE INDEX IF NOT EXISTS idx_movproductos_aseo
    ON movimientos_productos(id_aseo);

CREATE INDEX IF NOT EXISTS idx_movproductos_maternidad
    ON movimientos_productos(id_maternidad);

COMMIT;
